#!/bin/bash
set -euo pipefail
set -x

install_cni_plugins() {
    # If containernetworking-plugins is already installed, exit
    if rpm -q containernetworking-plugins &>/dev/null; then
        return 0
    fi

    # Set the package version and name
    CNP_VER=v1.8.0
    CNP_PKG="cni-plugins-linux-amd64-${CNP_VER}.tgz"
    [ "$(uname -m)" = "aarch64" ] && CNP_PKG="cni-plugins-linux-arm64-${CNP_VER}.tgz"

    # Download the package
    curl -fsSL --retry 5 -o "/tmp/${CNP_PKG}" \
        "https://github.com/containernetworking/plugins/releases/download/${CNP_VER}/${CNP_PKG}"

    # Extract the package into the CNI plugins directory as defined
    # in the crio.conf.d/13-microshift-kindnet.conf file.
    mkdir -p /usr/libexec/cni
    tar zxvf "/tmp/${CNP_PKG}" -C /usr/libexec/cni && \

    # Clean up
    rm -f "/tmp/${CNP_PKG}"
}

# Create the storage merger separately from the container configuration steps.
container_config_create_storage_script() {
    cat > "$1" <<'PY'
import os
from pathlib import Path
import sys
import tempfile

import tomli_w

try:
    import tomllib
except ModuleNotFoundError:
    import tomli as tomllib


def existing_config(path):
    if path.is_symlink() and not path.exists():
        raise ValueError(f"dangling configuration symlink: {path}")
    if path.exists():
        if not path.is_file():
            raise ValueError(f"expected a regular configuration file: {path}")
        return True
    return False


def configure(vendor, local):
    destination = local / "storage.conf"
    if existing_config(destination):
        return

    files = {}
    # A higher-priority directory masks files with the same basename. Selected
    # drop-ins are then applied in global filename order, as containers/storage does.
    for directory in (vendor, local):
        for name in ("storage.conf.d", "storage.rootful.conf.d"):
            for entry in (directory / name).glob("*.conf"):
                if not entry.is_dir():
                    files[entry.name] = entry
    sources = [vendor / "storage.conf"] + [files[name] for name in sorted(files)]

    config = {}
    append_priority = False

    def merge(target, incoming, path=()):
        nonlocal append_priority
        for key, value in incoming.items():
            current = path + (key,)
            if current == ("storage", "driver_priority"):
                # This storage field supports the upstream sticky {append=...}
                # attribute. Resolve it now so legacy CRI-O sees plain strings.
                if not isinstance(value, list):
                    raise ValueError("storage.driver_priority must be an array")
                items = []
                for item in value:
                    if isinstance(item, str):
                        items.append(item)
                    elif (isinstance(item, dict) and set(item) == {"append"}
                          and isinstance(item["append"], bool)):
                        append_priority = item["append"]
                    else:
                        raise ValueError("invalid storage.driver_priority item")
                target[key] = target.get(key, []) + items if append_priority else items
            elif isinstance(value, dict):
                if key not in target:
                    target[key] = {}
                if not isinstance(target[key], dict):
                    raise ValueError(f"conflicting table: {'.'.join(current)}")
                merge(target[key], value, current)
            else:
                target[key] = value

    for source in sources:
        try:
            with source.open("rb") as stream:
                merge(config, tomllib.load(stream))
        except (OSError, ValueError) as error:
            raise ValueError(f"{source}: {error}") from error

    content = "# Generated by MicroShift postinstall from rootful storage defaults.\n"
    content += tomli_w.dumps(config)
    if tomllib.loads(content) != config:
        raise ValueError("generated storage configuration failed validation")

    local.mkdir(parents=True, exist_ok=True)
    # A private temporary directory handles cleanup on both success and failure.
    with tempfile.TemporaryDirectory(dir=local, prefix=".storage.conf.") as directory:
        temporary = Path(directory) / "storage.conf"
        temporary.write_text(content, encoding="utf-8")
        temporary.chmod(0o644)
        try:
            # Publish atomically without replacing a concurrently created path.
            os.link(temporary, destination)
        except FileExistsError:
            existing_config(destination)


try:
    configure(Path(sys.argv[1]), Path(sys.argv[2]))
except (OSError, TypeError, ValueError) as error:
    sys.exit(f"ERROR: Cannot configure container storage: {error}")
PY
}

# Missing paths can be created; existing paths must resolve to the expected type.
container_config_check_path() {
    local -r path=$1 type=$2

    if [ -L "${path}" ] && [ ! -e "${path}" ]; then
        echo "ERROR: Dangling configuration symlink: ${path}" >&2
        return 1
    fi
    if [ ! -e "${path}" ]; then
        return 0
    fi
    if { [ "${type}" = file ] && [ -f "${path}" ]; } || \
       { [ "${type}" = directory ] && [ -d "${path}" ]; }; then
        return 0
    fi
    echo "ERROR: Expected configuration ${type}: ${path}" >&2
    return 1
}

# Validate administrator paths before deciding whether any defaults are missing.
container_config_validate_paths() {
    local -r config_dir=$1
    local destination

    # Validate directories separately from file destinations, before any copies.
    for destination in "${config_dir}" \
        "${config_dir}"/{registries.d,registries.conf.d,storage.conf.d,storage.rootful.conf.d}; do
        container_config_check_path "${destination}" directory || return 1
    done
    for destination in \
        "${config_dir}"/{policy.json,registries.conf,storage.conf} \
        "${config_dir}"/registries.d/*.yaml "${config_dir}"/registries.conf.d/*.conf \
        "${config_dir}"/storage.conf.d/*.conf "${config_dir}"/storage.rootful.conf.d/*.conf; do
        container_config_check_path "${destination}" file || return 1
    done
}

# Return success only when vendor-backed defaults are missing locally.
container_config_needs_update() {
    local -r vendor_dir=$1 config_dir=$2
    local source destination

    for source in "${vendor_dir}"/{policy.json,registries.conf} \
        "${vendor_dir}"/registries.d/*.yaml "${vendor_dir}"/registries.conf.d/*.conf; do
        [ -f "${source}" ] || continue
        destination="${config_dir}/${source#"${vendor_dir}/"}"
        if [ ! -f "${destination}" ]; then
            return 0
        fi
    done

    # A base file alone is the legacy layout; flatten only split vendor defaults.
    if [ -f "${vendor_dir}/storage.conf" ] && [ ! -f "${config_dir}/storage.conf" ] && \
       { [ -d "${vendor_dir}/storage.conf.d" ] || [ -d "${vendor_dir}/storage.rootful.conf.d" ]; }; then
        return 0
    fi
    return 1
}

container_config_apply() (
    local -r vendor_dir=/usr/share/containers
    local -r config_dir=/etc/containers
    local source destination name storage_workdir

    container_config_validate_paths "${config_dir}"
    if ! container_config_needs_update "${vendor_dir}" "${config_dir}"; then
        return 0
    fi

    # Vendor defaults may be shipped under /usr/share/containers.
    # Older CRI-O needs policy and registry settings under /etc/containers.
    # Preserve existing administrator files and valid symlinks.
    for name in policy.json registries.conf; do
        source="${vendor_dir}/${name}"
        destination="${config_dir}/${name}"
        if [ -f "${source}" ] && [ ! -f "${destination}" ]; then
            mkdir -p "${config_dir}"
            cp "${source}" "${destination}"
        fi
    done

    # Keep signature lookup settings together with the signature policy, and
    # include registry defaults such as short-name aliases and search registries.
    for source in "${vendor_dir}"/registries.d/*.yaml "${vendor_dir}"/registries.conf.d/*.conf; do
        [ -f "${source}" ] || continue
        destination="${config_dir}/${source#"${vendor_dir}/"}"
        if [ ! -f "${destination}" ]; then
            mkdir -p "$(dirname "${destination}")"
            cp "${source}" "${destination}"
        fi
    done

    # After copying policy and registry defaults, only storage work can remain.
    if ! container_config_needs_update "${vendor_dir}" "${config_dir}"; then
        return 0
    fi

    # Python itself must be provided by the host.
    if ! command -v python3 &>/dev/null; then
        echo "ERROR: python3 is required to configure container storage" >&2
        return 1
    fi

    # Install TOML packages in a temporary environment without changing the host's
    # Python packages. Older Python versions also need the tomli reader.
    storage_workdir=$(mktemp -d /tmp/microshift-storage-XXXXXX)
    trap 'rm -rf "${storage_workdir}"' EXIT
    if ! python3 -m venv "${storage_workdir}/venv"; then
        echo "ERROR: Container storage requires Python venv with pip support" >&2
        return 1
    fi
    if ! "${storage_workdir}/venv/bin/python" -m pip install --disable-pip-version-check --no-cache-dir \
        tomli-w 'tomli; python_version < "3.11"'; then
        echo "ERROR: Cannot install TOML packages required to configure container storage" >&2
        return 1
    fi

    # Older CRI-O reads only one storage.conf. Flatten the rootful defaults and
    # local drop-ins into that file rather than losing settings such as metacopy.
    container_config_create_storage_script "${storage_workdir}/configure-storage.py"
    "${storage_workdir}/venv/bin/python" "${storage_workdir}/configure-storage.py" \
        "${vendor_dir}" "${config_dir}"
)

#
# Main
#
# Check if the script is running as root
if [ "$(id -u)" -ne 0 ]; then
    echo "ERROR: This script must be run as root (use sudo)"
    exit 1
fi

# Configure container policy, registries, and rootful storage defaults.
# Make split vendor defaults available to older CRI-O versions.
container_config_apply

# Configure network and add some useful utilities
dnf install -y firewalld jq bash-completion
firewall-offline-cmd --zone=trusted --add-source=10.42.0.0/16
firewall-offline-cmd --zone=trusted --add-source=169.254.169.1
# Multinode clusters require connectivity on both apiserver and etcd
firewall-offline-cmd --zone=public --add-port=6443/tcp
firewall-offline-cmd --zone=public --add-port=2379/tcp
firewall-offline-cmd --zone=public --add-port=2380/tcp

# Configure limits for cAdvisor and kubelet
cat > /etc/sysctl.d/99-microshift.conf <<EOF
fs.inotify.max_user_watches = 524288
fs.inotify.max_user_instances = 16384
EOF

# With kindnet present:
# - No need for openvswitch service which is enabled by default once MicroShift
#   is installed. Disable the service to avoid the need to configure it.
# - Need to disable systemd-resolved service to allow proper host name resolution
#   in Bootc containers running in privileged mode.
# - May need to install the containernetworking-plugins package from the package
#   GitHub release page (e.g. CentOS 10).
if rpm -q microshift-kindnet &>/dev/null; then
    systemctl disable openvswitch      &>/dev/null || true
    systemctl disable systemd-resolved &>/dev/null || true

    install_cni_plugins
fi

# Create a link to the default kubeconfig.
# Note that the /root directory may be a symlink to /var/roothome and the target
# directory may not exist, depending on the operating system.
if [ ! -f /root/.kube/config ] ; then
    mkdir -p "$(readlink -f /root)/.kube"
    ln -sf /var/lib/microshift/resources/kubeadmin/kubeconfig /root/.kube/config
fi

# Enable the MicroShift service
systemctl enable microshift
